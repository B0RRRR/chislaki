"""

Трёхдиагональная матрица: ненулевые элементы стоят только на трёх
диагоналях. Поэтому вместо всей матрицы 5 x 5 храним 4 списка:
    a - поддиагональ,
    b - главная диагональ,
    c - наддиагональ,
    d - правые части.
Тогда i-е уравнение для всех строк записывается одинаково:
    a_i * x_{i-1}  +  b_i * x_i  +  c_i * x_{i+1}  =  d_i.
В первом уравнении нет x_0, поэтому a_1 = 0;
в последнем нет x_{n+1}, поэтому c_n = 0.

Идея метода:
    Из 1-го уравнения выражаем x1 через x2, подставляем во 2-е и выражаем
    x2 через x3, и т.д. Каждый раз получается формула одного вида:
        x_i = P_i * x_{i+1} + Q_i,
    где P_i, Q_i - "прогоночные коэффициенты".
    В последнем уравнении правого соседа нет, поэтому оно сразу даёт
    число: x_n = Q_n. Дальше идём обратно снизу вверх и находим все x.

    Прямой ход  (сверху вниз): считаем все P_i и Q_i.
    Обратный ход (снизу вверх): считаем все x_i.
"""


def print_vector(name, v, fmt="{:10.4f}"):
    """
    Печатает вектор v в одну строку с подписью name.
    """
    numbers = [fmt.format(x) for x in v]
    print(f"{name} = [" + " ".join(numbers) + " ]")


def tridiagonal_to_full(a, b, c):
    """
    Собирает полную матрицу n x n из трёх диагоналей.
    Нужна только для печати и проверки невязки

    В строке i:
        b[i] ставится на диагональ          -> M[i][i],
        a[i] ставится левее диагонали       -> M[i][i-1],
        c[i] ставится правее диагонали      -> M[i][i+1].
    """
    n = len(b)
    M = [[0.0] * n for _ in range(n)]      # матрица n x n из нулей
    for i in range(n):
        M[i][i] = b[i]
        # У первой строки (i = 0) нет элемента левее диагонали:
        # столбца с номером -1 не существует.
        if i > 0:
            M[i][i - 1] = a[i]
        # У последней строки (i = n-1) нет элемента правее диагонали:
        # столбца с номером n не существует.
        if i < n - 1:
            M[i][i + 1] = c[i]
    return M


def check_stability(a, b, c):
    """
    Проверка достаточного условия устойчивости прогонки:
        1) a_i != 0 и c_i != 0 для средних строк;
        2) |b_i| >= |a_i| + |c_i| для всех строк;
        3) хотя бы в одной строке неравенство строгое (>).

    при выполнении условия все |P_i| <= 1. В обратном ходе
    x_i = P_i x_{i+1} + Q_i ошибка в x_{i+1} умножается на P_i, значит
    ошибки округления при движении вверх не растут. """
    n = len(b)

    # 1) Средние строки: индексы 1 .. n-2.
    nonzero = True
    for i in range(1, n - 1):
        if a[i] == 0 or c[i] == 0:
            nonzero = False

    # 2) Диагональное преобладание во всех строках.
    dominance = True
    for i in range(n):
        if abs(b[i]) < abs(a[i]) + abs(c[i]):
            dominance = False

    # 3) Хотя бы одна строка со строгим неравенством.
    strict = False
    for i in range(n):
        if abs(b[i]) > abs(a[i]) + abs(c[i]):
            strict = True

    return nonzero and dominance and strict


# Метод прогонки
def tridiagonal_solve(a, b, c, d):
    """
    Решает трёхдиагональную систему методом прогонки.

    Параметры (все списки длины n):
        a - поддиагональ,
        b - главная диагональ;
        c - наддиагональ,
        d - правые части.

    Формулы:
        P_1 = -c_1 / b_1,  Q_1 = d_1 / b_1;
        P_i = -c_i / (b_i + a_i P_{i-1}),
        Q_i = (d_i - a_i Q_{i-1}) / (b_i + a_i P_{i-1}),   i = 2 .. n;
        x_n = Q_n,  x_i = P_i x_{i+1} + Q_i,   i = n-1 .. 1.
    """
    n = len(b)                  # число уравнений
    P = [0.0] * n               # P_1 .. P_n
    Q = [0.0] * n               # Q_1 .. Q_n

    # Прямой ход: считаем P и Q

    # Первое уравнение
    #   b_1 x_1 + c_1 x_2 = d_1
    # Выражаем x_1:
    #   x_1 = (-c_1 / b_1) * x_2 + (d_1 / b_1)  =  P_1 * x_2 + Q_1.
    # Отдельно от цикла, потому что предыдущего P_0 не существует.
    P[0] = -c[0] / b[0]
    Q[0] = d[0] / b[0]

    # Остальные уравнения
    for i in range(1, n):
        # i-е уравнение:  a_i x_{i-1} + b_i x_i + c_i x_{i+1} = d_i.
        # На прошлом шаге уже получили x_{i-1} = P_{i-1} x_i + Q_{i-1}.
        # Подставляем и собираем слагаемые с x_i:
        #   (b_i + a_i P_{i-1}) * x_i = -c_i * x_{i+1} + (d_i - a_i Q_{i-1}).
        # Скобка слева - общий знаменатель для P_i и Q_i.
        denom = b[i] + a[i] * P[i - 1]

        # если случилось - система плохая продолжать нет смысла.
        if denom == 0:
            raise ZeroDivisionError(f"Нулевой знаменатель на шаге i = {i + 1}")

        # Делим на знаменатель и получаем x_i = P_i x_{i+1} + Q_i:
        P[i] = -c[i] / denom
        Q[i] = (d[i] - a[i] * Q[i - 1]) / denom

        # Для последнего уравнения c[n-1] = 0, поэтому P[n-1] = 0
        # получается само


    # Обратный ход: считаем x
    x = [0.0] * n

    # Последнее неизвестное: x_n = P_n * x_{n+1} + Q_n, но P_n = 0,
    # поэтому x_n = Q_n - это уже готовое число.
    x[n - 1] = Q[n - 1]

    # Идём снизу вверх:
    for i in range(n - 2, -1, -1):
        # x[i+1] уже найден на предыдущем шаге цикла (он ниже).
        x[i] = P[i] * x[i + 1] + Q[i]
    return x, P, Q


def main():
    a = [0,   -7,  -7,   4,  -6]
    b = [-12, -11, 21, -13,  14]
    c = [-7,  -3,  -8,   5,   0]
    d = [-102, -92, -65, 38, -12]
    n = len(b)

    print("=" * 60)
    print("Задание 1.2. Метод прогонки")
    print("=" * 60)
    print_vector("a (поддиагональ)   ", a, fmt="{:6.0f}")
    print_vector("b (главная диаг.)  ", b, fmt="{:6.0f}")
    print_vector("c (наддиагональ)   ", c, fmt="{:6.0f}")
    print_vector("d (правые части)   ", d, fmt="{:6.0f}")
    print()

    # Полная матрица
    A = tridiagonal_to_full(a, b, c)
    print("Матрица системы:")
    for row in A:
        numbers = [f"{v:6.0f}" for v in row]
        print("  [" + " ".join(numbers) + " ]")
    print()

    # Проверка условия устойчивости
    if check_stability(a, b, c):
        print("Условие устойчивости |b_i| >= |a_i| + |c_i| выполнено.\n")
    else:
        # Условие только достаточное: прогонка может сработать и без него,
        # но гарантии нет. Поэтому предупреждаем, но всё равно считаем.
        print("достаточное условие устойчивости не выполнено")

    # Решение
    x, P, Q = tridiagonal_solve(a, b, c, d)

    # Таблица прогоночных коэффициентов
    print(" i |      P_i      |      Q_i")
    print("---+---------------+---------------")
    for i in range(n):
        # i + 1 - чтобы печатать номера как в методичке (с 1, а не с 0).
        print(f"{i + 1:2d} | {P[i]:13.6f} | {Q[i]:13.6f}")
    print()

    print("Решение СЛАУ:")
    for i in range(n):
        print(f"  x{i + 1} = {x[i]:.6f}")

    # Невязка r = A x - d
    # Подставляем найденный x обратно в систему. Если решение верное,
    # получаются нули (с точностью до ~1e-14 - ошибки округления).
    r = [0.0] * n
    for i in range(n):
        s = 0.0
        for j in range(n):
            s += A[i][j] * x[j]        # левая часть i-го уравнения
        r[i] = s - d[i]
    print_vector("Невязка A x - d", r, fmt="{:10.2e}")


if __name__ == "__main__":
    main()
