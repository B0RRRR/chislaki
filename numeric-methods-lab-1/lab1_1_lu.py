"""
Что делает программа:
    1. Раскладывает матрицу A в произведение  P A = L U, где
         L - нижняя треугольная матрица (единицы на диагонали),
         U - верхняя треугольная матрица,
         P - матрица перестановок строк.
    2. С помощью этого разложения:
         * решает систему A x = b,
         * считает определитель det A,
         * находит обратную матрицу A^(-1).
"""

# Порог: если ведущий элемент по модулю меньше этого числа, считаем его
# нулём. Сравнивать с точным нулём нельзя: из-за ошибок округления
ZERO_EPS = 1e-12


def print_matrix(name, M, fmt="{:10.4f}"):
    """
    Печатает матрицу M построчно с заголовком name.
    fmt - формат числа: "{:10.4f}" = 10 символов ширины, 4 знака после точки.
    """
    print(f"{name} =")
    for row in M:
        numbers = []
        for v in row:
            # печатаем их как 0, чтобы не было "-0.0000".
            if abs(v) <= 1e-12:
                v = 0.0
            numbers.append(fmt.format(v))
        print("  [" + " ".join(numbers) + " ]")
    print()


def print_vector(name, v, fmt="{:10.4f}"):
    """Печатает вектор v в одну строку."""
    numbers = [fmt.format(x) for x in v]
    print(f"{name} = [" + " ".join(numbers) + " ]")


def mat_mul(A, B):
    """
    Произведение матриц A и B -> матрица C (n x p).
    Элемент C[i][j] = сумма по k от A[i][k] * B[k][j]
    Используется только для проверок (P A = L U, A A^(-1) = E).
    """
    n = len(A) # число строк A
    m = len(B) # число строк B
    p = len(B[0]) # число столбцов B
    C = [[0.0] * p for _ in range(n)]
    for i in range(n):
        for j in range(p):
            s = 0.0
            for k in range(m):
                s += A[i][k] * B[k][j]
            C[i][j] = s
    return C


def mat_vec(A, x):
    """
    Умножение матрицы A на вектор x.
    i-я компонента результата = сумма по j от A[i][j] * x[j].
    Нужна для вычисления невязки A x - b.
    """
    n = len(A)
    result = [0.0] * n
    for i in range(n):
        s = 0.0
        for j in range(len(x)):
            s += A[i][j] * x[j]
        result[i] = s
    return result


def identity(n):
    """Единичная матрица порядка n: единицы на диагонали, остальное нули."""
    E = [[0.0] * n for _ in range(n)]
    for i in range(n):
        E[i][i] = 1.0
    return E



# LU-разложение
def lu_decompose(A):
    """
    LU-разложение с выбором главного элемента по столбцу: P A = L U.

    Возвращает четыре значения:
        L     - нижняя треугольная матрица с единицами на диагонали;
        U     - верхняя треугольная матрица;
        perm  - список-перестановка: perm[i] = номер строки исходной
                матрицы A, которая после всех перестановок оказалась
                на i-м месте. Это компактная запись матрицы P.
                Для варианта 26 получится perm = [1, 0, 3, 2]:
                на 1-м месте стоит исходная строка 2, на 2-м - строка 1,
                на 3-м - строка 4, на 4-м - строка 3.
        swaps - сколько раз переставляли строки (нужно для знака det A).
    """
    n = len(A)

    # Подготовка
    # U начинаем с копии матрицы A: над U выполняется прямой ход Гаусса,
    # и она будет меняться. Исходная A нам ещё понадобится в main()
    U = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            U[i][j] = float(A[i][j])

    # L пока заполнена нулями; множители mu будем записывать в неё
    # по ходу прямого хода.
    L = [[0.0] * n for _ in range(n)]

    # Пока перестановок не было: на i-м месте стоит i-я строка.
    perm = list(range(n))
    swaps = 0

    # Прямой ход: шаги k = 0, 1, , n-1
    # На шаге k обнуляем все элементы k-го столбца ниже диагонали.
    for k in range(n):

        # 1. Выбор ведущего элемента
        # Среди строк k, k+1, ..., n-1 ищем ту, у которой |U[i][k]|
        # наибольший. Её номер запоминаем в p.
        p = k
        for i in range(k + 1, n):
            if abs(U[i][k]) > abs(U[p][k]):
                p = i

        # Если даже самый большой элемент столбца почти ноль, значит весь
        # столбец под диагональю нулевой: det A = 0, матрица вырождена.
        if abs(U[p][k]) < ZERO_EPS:
            raise ValueError("ведущий элемент равен нулю")

        # 2. Перестановка строк k и p (если главный элемент не на месте)
        if p != k:
            # Меняем местами строки k и p в матрице U целиком.
            U[k], U[p] = U[p], U[k]

            # Запоминаем перестановку: теперь на месте k стоит та строка,
            # что была на месте p, и наоборот.
            perm[k], perm[p] = perm[p], perm[k]

            # В L переставляем только уже вычисленную часть -
            # столбцы 0 .. k-1. Там лежат множители с прошлых шагов,
            # и они принадлежат своим строкам
            for j in range(k):
                L[k][j], L[p][j] = L[p][j], L[k][j]

            swaps += 1

        # 3. Обнуление элементов k-го столбца ниже диагонали
        # Для каждой строки i ниже ведущей строки k:
        for i in range(k + 1, n):
            # во сколько раз элемент U[i][k] больше ведущего.
            # Благодаря выбору главного элемента всегда |mu| <= 1.
            mu = U[i][k] / U[k][k]

            # Этот множитель и есть элемент L[i][k] матрицы L.
            L[i][k] = mu

            # Из строки i вычитаем ведущую строку k, умноженную на mu:
            #     U[i][j] = U[i][j] - mu * U[k][j].
            # После этого U[i][k] станет 0.
            # Цикл начинается с j = k, потому что левее столбца k
            # в обеих строках всегда 0
            for j in range(k, n):
                U[i][j] = U[i][j] - mu * U[k][j]

        # 4. Единица на диагонали L
        L[k][k] = 1.0

    return L, U, perm, swaps


# Решение системы по разложению
def lu_solve(L, U, perm, b):
    """
    Решение системы Ax = b по разложению PA = LU.

    решение идёт в 2 этапа:
        1) L z = P b  - решаем сверху вниз (L):
               z_i = (Pb)_i - sum_{j<i} l_ij z_j;
        2) U x = z    - решаем снизу вверх (U):
               x_i = (z_i - sum_{j>i} u_ij x_j) / u_ii.
    """
    n = len(L)

    # 0. Переставляем правую часть так же, как строки A
    # perm[i] - номер исходной строки, стоящей теперь на i-м месте,
    # значит на i-е место ставим её правую часть b[perm[i]].
    pb = [0.0] * n
    for i in range(n):
        pb[i] = float(b[perm[i]])

    # 1. Прямая подстановка: L z = P b
    # Строка i системы L z = Pb:
    #   l_i1 z_1 + ... + l_i,i-1 z_{i-1} + 1 * z_i = pb_i.
    # Все z_1 .. z_{i-1} уже найдены на предыдущих шагах, переносим их
    # вправо. на диагонали L стоят единицы.
    z = [0.0] * n
    for i in range(n):
        s = 0.0
        for j in range(i):             # j = 0 .. i-1 (уже найденные z)
            s += L[i][j] * z[j]
        # при i = 0 цикл не выполняется, s = 0, и z[0] = pb[0]
        z[i] = pb[i] - s

    # 2. Обратная подстановка: U x = z (снизу вверх)
    # Строка i системы U x = z:
    #   u_ii x_i + u_i,i+1 x_{i+1} + ... + u_in x_n = z_i.
    # Идём с последней строки: там только x_n. Все x правее x_i к этому
    # моменту уже найдены, переносим их вправо и делим на u_ii.
    # range(n - 1, -1, -1) даёт i = n-1, n-2, ..., 0 (шаг -1, "назад").
    x = [0.0] * n
    for i in range(n - 1, -1, -1):
        s = 0.0
        for j in range(i + 1, n):      # j = i+1 .. n-1 (уже найденные x)
            s += U[i][j] * x[j]
        x[i] = (z[i] - s) / U[i][i]

    return x


# Определитель
def lu_determinant(U, swaps):
    """
    Определитель по LU-разложению:
        det A = (-1)^swaps * u_11 * u_22 * ... * u_nn.
    """
    # Знак: +1 при чётном числе перестановок, -1 при нечётном.
    if swaps % 2 == 0:
        det = 1.0
    else:
        det = -1.0

    # Умножаем на все диагональные элементы U.
    for i in range(len(U)):
        det = det * U[i][i]
    return det


# Обратная матрица
def lu_inverse(L, U, perm):
    """
    Обратная матрица X = A^(-1) - это решение уравнения A X = E.
    Разложение A уже готово, поэтому каждая система решается быстро -
    просто вызываем lu_solve с правой частью = столбец единичной матрицы.
    """
    n = len(L)
    E = identity(n)

    # columns[j] будет j-м столбцом обратной матрицы.
    columns = []
    for j in range(n):
        # Достаём j-й столбец единичной матрицы: (0, ..., 1, ..., 0).
        e_j = [0.0] * n
        for i in range(n):
            e_j[i] = E[i][j]
        # Решаем A x = e_j - это и есть j-й столбец A^(-1).
        columns.append(lu_solve(L, U, perm, e_j))

    # Матрица у нас хранится по строкам, а мы получили столбцы.
    # Поэтому транспонируем
    X = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            X[i][j] = columns[j][i]
    return X



def main():
    A = [
        [-2, -9, -3,  7],
        [-7,  8,  2,  5],
        [-6,  2,  0,  0],
        [ 0, -3,  8, -3],
    ]
    b = [-26, -25, -16, -5]
    n = len(A)

    print("Задание 1.1. LU-разложение (вариант 26)")
    print_matrix("A", A)
    print_vector("b", b)
    print()

    # LU-разложение
    L, U, perm, swaps = lu_decompose(A)

    # Для печати строим саму матрицу перестановок P из списка perm:
    # в строке i единица стоит в столбце perm[i], остальное нули.
    P = [[0.0] * n for _ in range(n)]
    for i in range(n):
        P[i][perm[i]] = 1.0

    print_matrix("L", L)
    print_matrix("U", U)
    print_matrix("P", P, fmt="{:4.0f}")
    print(f"Число перестановок строк: {swaps}\n")

    # Проверка разложения: P A должно совпадать с L U
    # Считаем максимальное расхождение между элементами P*A и L*U.
    PA = mat_mul(P, A)
    LU = mat_mul(L, U)
    err = 0.0
    for i in range(n):
        for j in range(n):
            if abs(PA[i][j] - LU[i][j]) > err:
                err = abs(PA[i][j] - LU[i][j])
    print(f"Проверка: max|PA - LU| = {err:.2e}\n")

    # Решение системы
    x = lu_solve(L, U, perm, b)
    print("Решение СЛАУ:")
    for i in range(n):
        print(f"  x{i + 1} = {x[i]:.6f}")

    # Невязка r = A x - b: подставляем найденный x обратно в систему.
    # Если решение верное, получаются нули (с точностью до ~1e-15 -
    # это ошибки округления компьютерной арифметики).
    Ax = mat_vec(A, x)
    r = [Ax[i] - b[i] for i in range(n)]
    print_vector("Невязка A x - b", r, fmt="{:10.2e}")
    print()

    # Определитель
    det = lu_determinant(U, swaps)
    print(f"det A = {det:.6f}\n")

    # Обратная матрица
    A_inv = lu_inverse(L, U, perm)
    print_matrix("A^(-1)", A_inv, fmt="{:10.6f}")

    # Проверка: A * A^(-1) должно дать единичную матрицу.
    AA = mat_mul(A, A_inv)
    print_matrix("Проверка A * A^(-1)", AA, fmt="{:10.6f}")


if __name__ == "__main__":
    main()
