"""
Что делает программа:
    Методом вращений Якоби находит собственные значения и собственные
    векторы симметрической матрицы A с заданной точностью eps.
    Дополнительно исследует, как погрешность зависит от числа итераций.

Матрица варианта 26:
        | -4  1  -7 |
    A = |  1  9   1 |
        | -7  1   7 |

Идея метода:
    Для симметрической матрицы существует ортогональная матрица U
    (U^T U = E), такая что
        Lambda = U^T A U
    - диагональная матрица, на диагонали которой стоят собственные
    значения A, а столбцы U - собственные векторы.

    Сразу такую U найти нельзя, поэтому строим её по частям: на каждом
    шаге "поворачиваем" матрицу так, чтобы обнулить один (самый большой)
    внедиагональный элемент. Постепенно все внедиагональные элементы
    становятся маленькими и матрица становится почти диагональной.

Алгоритм (A^(0) = A):
    1. Находим максимальный по модулю внедиагональный элемент a_ij^(k),
       i < j.
    2. Строим матрицу вращения U^(k): это единичная матрица, у которой
       изменены только 4 элемента:
           u_ii = u_jj = cos(phi),  u_ij = -sin(phi),  u_ji = sin(phi),
       а угол phi подбирается так, чтобы новый a_ij стал нулём:
           phi = 1/2 * arctg( 2 a_ij / (a_ii - a_jj) ),
           phi = pi/4, если a_ii = a_jj.
    3. A^(k+1) = U^(k)T A^(k) U^(k).
    4. Критерий окончания - малость внедиагональных элементов:
           t(A^(k+1)) = sqrt( sum_{l<m} (a_lm^(k+1))^2 ) < eps.
    После остановки:
        собственные значения - диагональ A^(k+1),
        собственные векторы  - столбцы матрицы U = U^(0) U^(1) ... U^(k).
"""

import math

# Максимально допустимое число итераций (защита от зацикливания).
MAX_ITER = 1000


def print_matrix(name, M, fmt="{:10.4f}"):
    """
    Печатает матрицу M построчно с заголовком name.
    fmt - формат числа: "{:10.4f}" = 10 символов ширины, 4 знака после точки.
    """
    print(f"{name} =")
    for row in M:
        numbers = [fmt.format(v) for v in row]
        print("  [" + " ".join(numbers) + " ]")
    print()


def identity(n):
    """Единичная матрица порядка n: единицы на диагонали, остальное нули."""
    E = [[0.0] * n for _ in range(n)]
    for i in range(n):
        E[i][i] = 1.0
    return E


def transpose(M):
    """
    Транспонирование: строки становятся столбцами.
    Элемент T[i][j] = M[j][i].
    """
    n = len(M)         # число строк M
    m = len(M[0])      # число столбцов M
    T = [[0.0] * n for _ in range(m)]
    for i in range(m):
        for j in range(n):
            T[i][j] = M[j][i]
    return T


def mat_mul(A, B):
    """
    Произведение матриц A и B -> матрица C (n x p).
    Элемент C[i][j] = сумма по k от A[i][k] * B[k][j].
    """
    n = len(A)         # число строк A
    m = len(B)         # число строк B
    p = len(B[0])      # число столбцов B
    C = [[0.0] * p for _ in range(n)]
    for i in range(n):
        for j in range(p):
            s = 0.0
            for k in range(m):
                s += A[i][k] * B[k][j]
            C[i][j] = s
    return C


def mat_vec(A, x):
    """
    Умножение матрицы A на вектор x.
    i-я компонента результата = сумма по j от A[i][j] * x[j].
    Нужна для проверки A x = lambda x.
    """
    n = len(A)
    result = [0.0] * n
    for i in range(n):
        s = 0.0
        for j in range(len(x)):
            s += A[i][j] * x[j]
        result[i] = s
    return result


def is_symmetric(A, tol=1e-12):
    """
    Проверка симметричности A = A^T, т.е. a_ij = a_ji для всех i, j.
    Метод вращений применим только к симметрическим матрицам: только
    для них существует ортогональная U, приводящая A к диагональному виду.
    Проверяем элементы выше диагонали и сравниваем с зеркальными.
    tol - допуск на ошибки округления.
    """
    n = len(A)
    for i in range(n):
        for j in range(i + 1, n):
            if abs(A[i][j] - A[j][i]) > tol:
                return False
    return True


def off_diagonal_norm(A):
    """
    t(A) = sqrt( sum_{l<m} a_lm^2 ) - критерий окончания итераций.

    Это "размер" всех внедиагональных элементов вместе. Когда t(A) мало,
    матрица почти диагональная.
    Матрица симметрическая (a_lm = a_ml), поэтому достаточно суммировать
    только элементы выше диагонали (m > l).
    """
    n = len(A)
    s = 0.0
    for l in range(n):
        for m in range(l + 1, n):     # только элементы правее диагонали
            s += A[l][m] ** 2
    return math.sqrt(s)


# Метод вращений Якоби
def jacobi_rotation(A, eps):
    """
    Метод вращений Якоби.

    Возвращает четыре значения:
        eigenvalues - список собственных значений (диагональ A^(k));
        U_total     - матрица, столбцы которой - собственные векторы;
        k           - число выполненных итераций (вращений);
        history     - список значений t(A^(k)) после каждой итерации
                      (нужен для анализа погрешности).
    """
    if not is_symmetric(A):
        raise ValueError("Матрица не симметрическая, метод вращений неприменим")

    n = len(A)

    # Подготовка
    # Ak - текущая матрица A^(k). Начинаем с копии A (с переводом в float):
    # Ak на каждой итерации заменяется новой матрицей, а исходная A
    # нам ещё понадобится в main() для проверки A x = lambda x.
    Ak = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            Ak[i][j] = float(A[i][j])

    # U_total - накопленное произведение U^(0) U^(1) ... U^(k).
    # До первого вращения произведение "пустое", т.е. единичная матрица.
    U_total = identity(n)

    history = []  # сюда складываем t(A^(k)) после каждой итерации

    # Итерации
    # k принимает значения 1, 2, 3, ..., MAX_ITER.
    for k in range(1, MAX_ITER + 1):

        # 1. Поиск максимального по модулю внедиагонального элемента
        # Смотрим только выше диагонали (m > l): ниже стоят те же числа.
        # Начинаем с a_01 (первый элемент выше диагонали) и заменяем его,
        # если нашли элемент больше по модулю.
        # Обнуляем именно самый большой элемент - так t(A) убывает быстрее
        # всего (на каждом шаге сумма квадратов внедиагональных элементов
        # уменьшается ровно на 2 * a_ij^2).
        i, j = 0, 1
        for l in range(n):
            for m in range(l + 1, n):
                if abs(Ak[l][m]) > abs(Ak[i][j]):
                    i, j = l, m

        # 2. Угол вращения
        # Если расписать произведение U^T A U, то новый элемент a_ij равен
        #     a_ij * cos(2 phi) + (a_jj - a_ii) / 2 * sin(2 phi).
        # Приравниваем к нулю и получаем tg(2 phi) = 2 a_ij / (a_ii - a_jj).
        # Если a_ii = a_jj, то знаменатель ноль (tg = бесконечность),
        # т.е. 2 phi = pi/2, откуда phi = pi/4.
        # Сравнение с точным нулём здесь допустимо: при почти равных
        # a_ii и a_jj дробь просто большая, а arctg от большого числа
        # стремится к pi/2 - формула не ломается.
        if Ak[i][i] == Ak[j][j]:
            phi = math.pi / 4
        else:
            phi = 0.5 * math.atan(2 * Ak[i][j] / (Ak[i][i] - Ak[j][j]))

        # Матрица вращения U^(k): отличается от единичной только
        # четырьмя элементами на пересечении строк/столбцов i и j.
        # Это поворот на угол phi в плоскости осей i и j; остальные
        # координаты не меняются. Такая матрица ортогональная:
        # U^T U = E, поэтому U^T = U^(-1) и U^T A U - преобразование
        # подобия (собственные значения не меняются).
        c = math.cos(phi)
        s = math.sin(phi)
        U = identity(n)
        U[i][i] = c
        U[j][j] = c
        U[i][j] = -s
        U[j][i] = s

        # 3. Преобразование подобия A^(k+1) = U^T A^(k) U
        # После него a_ij и a_ji становятся нулями. Но элементы в строках
        # и столбцах i, j тоже меняются, и обнулённые на прошлых шагах
        # элементы могут снова стать ненулевыми. Поэтому за одно вращение
        # на каждый элемент задачу не решить - нужны итерации.
        # Матрица остаётся симметрической.
        Ak = mat_mul(mat_mul(transpose(U), Ak), U)

        # Накапливаем произведение матриц вращения:
        # U_total = U^(0) U^(1) ... U^(k).
        # Тогда A^(k+1) = U_total^T A U_total. Когда A^(k+1) станет почти
        # диагональной (= Lambda), получим A U_total = U_total Lambda,
        # т.е. m-й столбец U_total - собственный вектор для lambda_m.
        U_total = mat_mul(U_total, U)

        # 4. Проверка окончания
        t = off_diagonal_norm(Ak)
        history.append(t)                  # запоминаем для анализа
        if t < eps:
            # Матрица почти диагональная - её диагональ и есть
            # собственные значения.
            eigenvalues = [0.0] * n
            for m in range(n):
                eigenvalues[m] = Ak[m][m]
            return eigenvalues, U_total, k, history

    # если ошибка
    raise RuntimeError(f"Метод вращений не сошёлся за {MAX_ITER} итераций")


def main():
    # Исходные данные
    A = [
        [-4, 1, -7],
        [ 1, 9,  1],
        [-7, 1,  7],
    ]
    eps = 0.01                             # заданная точность
    n = len(A)

    print("=" * 60)
    print("Задание 1.4. Метод вращений Якоби (вариант 26)")
    print("=" * 60)
    print_matrix("A", A, fmt="{:6.0f}")
    print(f"Точность eps = {eps}\n")

    # Решение
    # Функция возвращает четыре значения - сразу раскладываем их
    # в четыре переменные.
    eigenvalues, U, k, history = jacobi_rotation(A, eps)

    print(f"Число итераций: {k}\n")
    print("Собственные значения:")
    for m in range(n):
        print(f"  lambda{m + 1} = {eigenvalues[m]:.6f}")
    print()

    print_matrix("Матрица U (столбцы - собственные векторы)", U, fmt="{:10.6f}")

    # Проверка: A x = lambda x для каждой пары
    # Подставляем найденные lambda и x в определение собственного вектора
    # и считаем невязку ||A x - lambda x|| (евклидова норма).
    # Она должна быть маленькой - порядка eps или меньше.
    print("Проверка ||A x - lambda x|| для каждого собственного вектора:")
    for m in range(n):
        # Собственный вектор x - это m-й СТОЛБЕЦ матрицы U,
        # поэтому собираем его из элементов U[r][m] по всем строкам r.
        x = [0.0] * n
        for r in range(n):
            x[r] = U[r][m]

        Ax = mat_vec(A, x)

        # residual = sqrt( sum_r (Ax_r - lambda * x_r)^2 )
        s = 0.0
        for r in range(n):
            s += (Ax[r] - eigenvalues[m] * x[r]) ** 2
        residual = math.sqrt(s)

        numbers = [f"{v:9.5f}" for v in x]
        print(f"  x{m + 1} = [" + " ".join(numbers) + " ]"
              f"   ||A x - lambda x|| = {residual:.2e}")
    print()

    # Проверка ортогональности собственных векторов
    # У симметрической матрицы собственные векторы взаимно ортогональны.
    # U - произведение ортогональных матриц вращения, значит тоже
    # ортогональная: скалярное произведение разных столбцов равно 0.
    print("Скалярные произведения собственных векторов (должны быть ~0):")
    for p in range(n):
        for q in range(p + 1, n):          # каждую пару (p, q) берём один раз
            # (x_p, x_q) = sum_r U[r][p] * U[r][q]
            dot = 0.0
            for r in range(n):
                dot += U[r][p] * U[r][q]
            print(f"  (x{p + 1}, x{q + 1}) = {dot:.2e}")
    print()

    # Анализ: погрешность в зависимости от номера итерации
    # Погрешность характеризуем величиной t(A^(k)) - корнем из суммы
    # квадратов внедиагональных элементов. Для симметрической матрицы
    # собственные значения отличаются от диагональных элементов A^(k)
    # не более чем на t(A^(k)), так что это и есть оценка погрешности.
    # Для анализа запускаем метод с очень маленьким eps, чтобы увидеть
    # всю картину убывания погрешности.
    # Нужна только history (четвёртое значение), остальное пишем в "_".
    _, _, _, full_history = jacobi_rotation(A, 1e-12)
    print("Зависимость погрешности t(A^(k)) от числа итераций k:")
    print("   k |    t(A^(k))    | t(A^(k)) / t(A^(k-1))")
    print("-----+----------------+----------------------")
    # Строка k = 0 - исходная матрица, до всех вращений.
    prev = off_diagonal_norm(A)
    print(f"{0:4d} | {prev:14.6e} |")
    for kk in range(len(full_history)):
        t = full_history[kk]
        # Во сколько раз уменьшилась погрешность за эту итерацию.
        # Если отношение с каждым шагом становится всё меньше - сходимость
        # ускоряется (быстрее, чем линейная).
        if prev > 0:
            ratio = t / prev
        else:
            ratio = 0.0
        print(f"{kk + 1:4d} | {t:14.6e} | {ratio:20.6f}")
        prev = t
    print()

    # Анализ: число итераций в зависимости от точности
    # Запускаем метод для eps = 0.1, 0.01, ..., 1e-10 и смотрим,
    # сколько итераций понадобилось.
    print("Число итераций в зависимости от заданной точности:")
    print("    eps    | итераций")
    print("-----------+---------")
    for p in range(1, 11):
        e = 10.0 ** (-p)                   # e = 10^(-p)
        # Нужно только число итераций (третье значение).
        _, _, kk, _ = jacobi_rotation(A, e)
        print(f"  1e-{p:<2d}    | {kk:7d}")
    print()
    print("Вывод: погрешность t(A^(k)) убывает с ростом числа итераций,\n"
          "причём на последних итерациях убывание ускоряется (сходимость\n"
          "метода Якоби асимптотически квадратичная), поэтому повышение\n"
          "точности в 10 раз требует всё меньше дополнительных итераций.")


if __name__ == "__main__":
    main()
