"""
Лабораторная работа 1, задание 1.4. Вариант 26.

Метод вращений Якоби: нахождение собственных значений и собственных
векторов симметрической матрицы. Входные данные: матрица и точность.
Дополнительно анализируется зависимость погрешности от числа итераций.

Матрица варианта 26:
        | -4  1  -7 |
    A = |  1  9   1 |
        | -7  1   7 |

Теория (методичка, п. 1.2.2).
Для симметрической матрицы существует ортогональная U, такая что
Lambda = U^T A U - диагональная матрица с собственными значениями.
U строится как произведение матриц вращения.

Алгоритм (A^(0) = A):
 1. Выбирается максимальный по модулю внедиагональный элемент a_ij^(k),
    i < j.
 2. Строится матрица вращения U^(k): это единичная матрица, у которой
        u_ii = u_jj = cos(phi),  u_ij = -sin(phi),  u_ji = sin(phi),
    где угол подбирается так, чтобы обнулить a_ij:
        phi = 1/2 * arctg( 2 a_ij / (a_ii - a_jj) ),
        phi = pi/4, если a_ii = a_jj.
 3. A^(k+1) = U^(k)T A^(k) U^(k).
 4. Критерий окончания - малость внедиагональных элементов:
        t(A^(k+1)) = sqrt( sum_{l<m} (a_lm^(k+1))^2 ) < eps.
 После остановки: собственные значения - диагональ A^(k+1),
 собственные векторы - столбцы матрицы U = U^(0) U^(1) ... U^(k).

Программа написана на "чистом" Python без сторонних библиотек.
"""

import math

MAX_ITER = 1000  # защита от зацикливания


# ----------------------------------------------------------------------
#                    Вспомогательные функции
# ----------------------------------------------------------------------

def print_matrix(name, M, fmt="{:10.4f}"):
    """Печатает матрицу M с заголовком name."""
    print(f"{name} =")
    for row in M:
        print("  [" + " ".join(fmt.format(v) for v in row) + " ]")
    print()


def identity(n):
    """Единичная матрица порядка n."""
    return [[1.0 if i == j else 0.0 for j in range(n)] for i in range(n)]


def transpose(M):
    """Транспонирование матрицы."""
    return [list(col) for col in zip(*M)]


def mat_mul(A, B):
    """Произведение матриц."""
    n, m, p = len(A), len(B), len(B[0])
    return [[sum(A[i][k] * B[k][j] for k in range(m)) for j in range(p)]
            for i in range(n)]


def mat_vec(A, x):
    """Произведение матрицы на вектор."""
    return [sum(a * xj for a, xj in zip(row, x)) for row in A]


def is_symmetric(A, tol=1e-12):
    """Проверка A = A^T - метод вращений применим только к таким матрицам."""
    n = len(A)
    return all(abs(A[i][j] - A[j][i]) <= tol
               for i in range(n) for j in range(i + 1, n))


def off_diagonal_norm(A):
    """
    t(A) = sqrt( sum_{l<m} a_lm^2 ) - критерий окончания итераций.
    Суммируем только над диагональю (матрица симметрическая).
    """
    n = len(A)
    return math.sqrt(sum(A[l][m] ** 2 for l in range(n) for m in range(l + 1, n)))


# ----------------------------------------------------------------------
#                       Метод вращений Якоби
# ----------------------------------------------------------------------

def jacobi_rotation(A, eps):
    """
    Метод вращений Якоби.

    Возвращает (eigenvalues, U, k, history):
        eigenvalues - список собственных значений (диагональ A^(k));
        U           - матрица, столбцы которой - собственные векторы;
        k           - число выполненных итераций (вращений);
        history     - список значений t(A^(k)) после каждой итерации.
    """
    if not is_symmetric(A):
        raise ValueError("Матрица не симметрическая, метод вращений неприменим")

    n = len(A)
    Ak = [list(map(float, row)) for row in A]   # текущая матрица A^(k)
    U_total = identity(n)                       # накопленное произведение U^(0)...U^(k)
    history = []

    for k in range(1, MAX_ITER + 1):
        # --- 1. Поиск максимального по модулю внедиагонального элемента ---
        i, j = 0, 1
        for l in range(n):
            for m in range(l + 1, n):
                if abs(Ak[l][m]) > abs(Ak[i][j]):
                    i, j = l, m

        # --- 2. Угол вращения ---
        if Ak[i][i] == Ak[j][j]:
            phi = math.pi / 4
        else:
            phi = 0.5 * math.atan(2 * Ak[i][j] / (Ak[i][i] - Ak[j][j]))

        # Матрица вращения U^(k): отличается от единичной только
        # четырьмя элементами на пересечении строк/столбцов i и j.
        U = identity(n)
        c, s = math.cos(phi), math.sin(phi)
        U[i][i] = c
        U[j][j] = c
        U[i][j] = -s
        U[j][i] = s

        # --- 3. Преобразование подобия A^(k+1) = U^T A^(k) U ---
        Ak = mat_mul(mat_mul(transpose(U), Ak), U)
        # Накапливаем произведение матриц вращения - его столбцы
        # в конце станут собственными векторами.
        U_total = mat_mul(U_total, U)

        # --- 4. Критерий окончания ---
        t = off_diagonal_norm(Ak)
        history.append(t)
        if t < eps:
            eigenvalues = [Ak[m][m] for m in range(n)]
            return eigenvalues, U_total, k, history

    raise RuntimeError(f"Метод вращений не сошёлся за {MAX_ITER} итераций")


# ----------------------------------------------------------------------
#                            Основная программа
# ----------------------------------------------------------------------

def main():
    # Данные варианта 26.
    A = [
        [-4, 1, -7],
        [ 1, 9,  1],
        [-7, 1,  7],
    ]
    eps = 0.01
    n = len(A)

    print("=" * 60)
    print("Задание 1.4. Метод вращений Якоби (вариант 26)")
    print("=" * 60)
    print_matrix("A", A, fmt="{:6.0f}")
    print(f"Точность eps = {eps}\n")

    eigenvalues, U, k, history = jacobi_rotation(A, eps)

    print(f"Число итераций: {k}\n")
    print("Собственные значения:")
    for m, lam in enumerate(eigenvalues, 1):
        print(f"  lambda{m} = {lam:.6f}")
    print()

    print_matrix("Матрица U (столбцы - собственные векторы)", U, fmt="{:10.6f}")

    # --- Проверка: A x = lambda x для каждой пары ---
    print("Проверка ||A x - lambda x|| для каждого собственного вектора:")
    for m in range(n):
        x = [U[r][m] for r in range(n)]          # m-й столбец U
        Ax = mat_vec(A, x)
        residual = math.sqrt(sum((Ax[r] - eigenvalues[m] * x[r]) ** 2
                                 for r in range(n)))
        print(f"  x{m + 1} = [" + " ".join(f"{v:9.5f}" for v in x) + " ]"
              f"   ||A x - lambda x|| = {residual:.2e}")
    print()

    # --- Проверка ортогональности собственных векторов ---
    print("Скалярные произведения собственных векторов (должны быть ~0):")
    for p in range(n):
        for q in range(p + 1, n):
            dot = sum(U[r][p] * U[r][q] for r in range(n))
            print(f"  (x{p + 1}, x{q + 1}) = {dot:.2e}")
    print()

    # --- Анализ: погрешность в зависимости от номера итерации ---
    # Погрешность характеризуем величиной t(A^(k)) - корнем из суммы
    # квадратов внедиагональных элементов. Для симметрической матрицы
    # собственные значения отличаются от диагональных элементов A^(k)
    # не более чем на t(A^(k)), так что это и есть оценка погрешности.
    # Для анализа запускаем метод с очень маленьким eps, чтобы увидеть
    # всю картину убывания погрешности.
    _, _, _, full_history = jacobi_rotation(A, 1e-12)
    print("Зависимость погрешности t(A^(k)) от числа итераций k:")
    print("   k |    t(A^(k))    | t(A^(k)) / t(A^(k-1))")
    print("-----+----------------+----------------------")
    prev = off_diagonal_norm(A)
    print(f"{0:4d} | {prev:14.6e} |")
    for kk, t in enumerate(full_history, 1):
        ratio = t / prev if prev > 0 else 0.0
        print(f"{kk:4d} | {t:14.6e} | {ratio:20.6f}")
        prev = t
    print()

    # --- Анализ: число итераций в зависимости от точности ---
    print("Число итераций в зависимости от заданной точности:")
    print("    eps    | итераций")
    print("-----------+---------")
    for p in range(1, 11):
        e = 10.0 ** (-p)
        _, _, kk, _ = jacobi_rotation(A, e)
        print(f"  1e-{p:<2d}    | {kk:7d}")
    print()
    print("Вывод: погрешность t(A^(k)) убывает с ростом числа итераций,\n"
          "причём на последних итерациях убывание ускоряется (сходимость\n"
          "метода Якоби асимптотически квадратичная), поэтому повышение\n"
          "точности в 10 раз требует всё меньше дополнительных итераций.")


if __name__ == "__main__":
    main()
